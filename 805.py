while True:
    cid = input("请输入15位不含校验码的银联信用卡号，输入0退出：")
    
    if cid == "0":
        break
    elif len(cid) != 15:
        print("请输入15位不含校验码的银联信用卡号")
        continue
    
    # 奇数位（索引0,2,4,...）乘以2后各位数字之和
    sum1 = sum(
        (int(ch) * 2) // 10 + (int(ch) * 2) % 10
        for ch in cid[::2]
    )
    
    # 偶数位（索引1,3,5,...）直接求和
    sum2 = sum(int(ch) for ch in cid[1::2])
    
    total = sum1 + sum2
    check_digit = 0 if total % 10 == 0 else 10 - total % 10
    
    print(f"完整的卡号是：{cid}{check_digit}")