# 银联信用卡校验码为卡号最后1位，采用的是LUHN算法，亦称模10算法。
# 计算方法如下。第1步：从左边第1个数字开始每隔1位乘以2。
# 第2步：把在第1步中获得的每组乘积逐位数字（个位与十位）相加，然后再与原卡号中未乘2的各位数字相加求和。
# 第3步：求10与第2步求和值的个位数之差，如果个位数为0，则该校验码为0。例如：625965087177209（不含最后1位的卡号）
# 第1步：6×2=12，5×2=10，6×2=12，0×2=0，7×2=14，7×2=14，2×2=4，9×2=18 
# 第2步：(1+2) + (1+0) + (1+2) + (0) + (1+4) + (1+4) + (4) + (1+8) = 30 30 + 2+9+5+8+1+7+0 = 62 
# 第3步：10-2=8 
# 所以，校验码是8，完整的卡号应该是6259650871772098。
